/**
 * Derives `src/components/manifest.ts` from the global-registration map in
 * `src/components/index.ts`.
 *
 * One list, three consumers: the bundler plugin's resolver (which needs to
 * turn `<NbButton>` into an import), the build (which needs one entry point
 * per component), and the `components.d.ts` the plugin emits for editors.
 * Deriving it means the three cannot drift from the set the library actually
 * ships.
 *
 * The file is generated and committed so that lint, format and type-check see
 * it like any other source; the build regenerates it first, so a component
 * added to `index.ts` and nothing else still gets an entry point.
 */
import { readFileSync, writeFileSync } from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const indexPath = path.join(root, 'src/components/index.ts')
const outPath = path.join(root, 'src/components/manifest.ts')

const source = readFileSync(indexPath, 'utf8')

// `import NbButton from './Button.vue'` → NbButton: Button
const imports = new Map()
for (const match of source.matchAll(
  /^import\s+(Nb[A-Za-z0-9]+)\s+from\s+'\.\/(.+)\.vue'$/gm,
)) {
  imports.set(match[1], match[2])
}

// Only the names actually registered, in the order the map lists them.
const registered = source
  .slice(source.indexOf('const components = {'))
  .match(/^\s{2}(Nb[A-Za-z0-9]+),$/gm)
  .map((line) => line.trim().replace(',', ''))

const missing = registered.filter((name) => !imports.has(name))
if (missing.length) {
  throw new Error(
    `components/index.ts registers ${missing.join(', ')} without a matching .vue import`,
  )
}

const entries = registered
  .map((name) => `  ${name}: '${imports.get(name)}',`)
  .join('\n')

writeFileSync(
  outPath,
  `/**
 * Every component the library registers, mapped to its path under
 * \`src/components\` (and therefore its published entry point,
 * \`@nubisco/ui/components/<path>\`).
 *
 * GENERATED by scripts/generate-component-manifest.mjs from
 * src/components/index.ts. Do not edit by hand.
 */
export const COMPONENT_MANIFEST = {
${entries}
} as const

export type TComponentName = keyof typeof COMPONENT_MANIFEST

export default COMPONENT_MANIFEST
`,
)

console.log(`wrote manifest for ${registered.length} components`)
